"""Contratos funcionales: ningún DTO HTTP, SQL o de proveedor."""
from typing import Protocol, ContextManager
from datetime import datetime
from .models import (Event, Seat, Client, Order, Quote, Ticket, TicketClaims,
                     PaymentRequest, PaymentSession, PaymentReference, VerifiedPayment, Delivery)


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdSource(Protocol):
    def new(self) -> str: ...


class Catalog(Protocol):
    def events(self) -> tuple[Event, ...]: ...
    def event(self, event_id: str) -> Event: ...
    def seats(self, venue_id: str) -> tuple[Seat, ...]: ...


class OrderStore(Protocol):
    def transaction(self) -> ContextManager[None]: ...
    def orders(self) -> tuple[Order, ...]: ...
    def order(self, order_id: str) -> Order: ...
    def save_order(self, order: Order) -> None: ...
    def tickets(self, order_id: str) -> tuple[Ticket, ...]: ...
    def save_ticket(self, ticket: Ticket) -> None: ...
    def deliveries(self) -> tuple[Delivery, ...]: ...
    def save_delivery(self, delivery: Delivery) -> None: ...


class PaymentGateway(Protocol):
    def register(self, request: PaymentRequest) -> PaymentSession: ...
    def verify(self, reference: PaymentReference) -> VerifiedPayment: ...


class TicketSigner(Protocol):
    def sign(self, claims: TicketClaims) -> str: ...
    def verify(self, claims: TicketClaims, signature: str) -> bool: ...


class TicketRenderer(Protocol):
    def render(self, ticket: Ticket, event: Event, seat: Seat) -> str: ...


class Notification(Protocol):
    def send(self, order: Order, tickets: tuple[Ticket, ...], key: str) -> None: ...


class Invoice(Protocol):
    def issue(self, order: Order, key: str) -> None: ...


class BookingUseCases(Protocol):
    def events(self) -> tuple[Event, ...]: ...
    def availability(self, event_id: str) -> tuple[Seat, ...]: ...
    def quote(self, event_id: str, seat_ids: tuple[str, ...]) -> Quote: ...
    def reserve(self, event_id: str, client: Client, seat_ids: tuple[str, ...], provider: str) -> Order: ...
    def confirm(self, provider: str, reference: PaymentReference) -> Order: ...
    def expire(self) -> int: ...
    def get_order(self, order_id: str) -> Order: ...
    def tickets(self, order_id: str) -> tuple[Ticket, ...]: ...
    def ticket_svg(self, order_id: str, ticket_id: str) -> str: ...
    def verify_ticket(self, order_id: str, ticket_id: str) -> bool: ...
    def dispatch(self) -> int: ...
